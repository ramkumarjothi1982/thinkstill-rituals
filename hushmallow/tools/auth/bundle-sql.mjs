// Bundles the Supabase SQL for the owner's production setup (supabase/production/RUNBOOK.md):
//   supabase/production/ALL_MIGRATIONS.sql  supabase/migrations/0001 … 0009, in order, byte for byte
//   supabase/production/RLS_CHECK.sql       supabase/tests/rls_check.sql, byte for byte
// Each file is a short generated header (comment lines only) and then the sources exactly as they are, so
// pasting the bundle runs exactly what the migrations run, and nothing else. A one-line comment names each
// migration before it. tests/auth-bundle.test.mjs rebuilds both files and fails on any difference, so
// the bundle can never drift from the migrations; tools/auth/sql-check.sh runs the bundle as one query
// string each (the way the SQL editor sends a pasted script) on a throwaway local PostgreSQL.
//
//   node hushmallow/tools/auth/bundle-sql.mjs            write both files
//   node hushmallow/tools/auth/bundle-sql.mjs --check    exit 1 if either is out of date (writes nothing)
//   import { bundleSql } from './bundle-sql.mjs'         → { files: { name: text }, migrations, checks }
// No network, no project, no secret: it only reads and writes files in this repository.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
export const MIGRATIONS_DIR = join(root, 'supabase/migrations');
export const RLS_CHECK_FILE = join(root, 'supabase/tests/rls_check.sql');
export const OUT_DIR = join(root, 'supabase/production');
export const MIGRATIONS_NAME = 'ALL_MIGRATIONS.sql';
export const RLS_CHECK_NAME = 'RLS_CHECK.sql';

/** The migration files in run order (0001_…sql, 0002_…sql, …); throws on a gap or a duplicate number. */
export function migrationFiles(dir = MIGRATIONS_DIR) {
  const files = readdirSync(dir).filter((f) => /^\d{4}_[a-z0-9_]+\.sql$/.test(f)).sort();
  files.forEach((f, i) => { if (Number(f.slice(0, 4)) !== i + 1) throw new Error(`supabase/migrations: expected ${String(i + 1).padStart(4, '0')}_….sql, found ${f}`); });
  if (!files.length) throw new Error('supabase/migrations: no migrations');
  return files;
}

/**
 * How many checks rls_check.sql counts (the N in "ALL N CHECKS PASSED"), read from the file itself: each
 * `total := total + 1; if not ok …` is one check, times the length of the `foreach … in array array[…] loop`
 * it sits in. (The early-stop handler's `fails := fails + 1; total := total + 1;` only counts on a failure.)
 */
export function countRlsChecks(sql) {
  const body = String(sql).replace(/--[^\n]*/g, '');
  const one = /total := total \+ 1; if not ok/g;
  let n = 0, rest = body;
  for (const m of body.matchAll(/foreach \w+ in array array\[([^\]]*)\] loop([\s\S]*?)end loop;/g)) {
    n += m[1].split(',').filter((x) => x.trim()).length * (m[2].match(one) || []).length;
    rest = rest.replace(m[0], '');
  }
  return n + (rest.match(one) || []).length;
}

const range = (files) => `${files[0].slice(0, 4)} … ${files[files.length - 1].slice(0, 4)}`;

function migrationsHeader(files, checks) {
  return [
    `-- hushmallow · production · ALL MIGRATIONS (${range(files)}, in order)`,
    '--',
    '-- GENERATED by hushmallow/tools/auth/bundle-sql.mjs from supabase/migrations/, byte for byte. Do not',
    '-- edit this file: change a migration, then run `node hushmallow/tools/auth/bundle-sql.mjs`',
    '-- (tests/auth-bundle.test.mjs fails if this file and the migrations differ).',
    '--',
    '-- Run it ONCE in the Supabase SQL editor of project hushmallow1 (ref igbxbfuaoybfzsroxuln, Sydney):',
    '-- SQL Editor → New query → paste this whole file → Run, as the default `postgres` role. Confirm the',
    '-- editor\'s "destructive operation" warning (the scripts replace their own policies and triggers; they',
    '-- never drop data). Expect "Success. No rows returned". Each migration is its own transaction and safe',
    '-- to run again: if the editor stops with an error, fix the cause and run this whole file again.',
    '--',
    `-- Then run ${RLS_CHECK_NAME} (next to this file) in a new query. It must end with`,
    `--   ALL ${checks} CHECKS PASSED. Everything this script created was rolled back.`,
    '-- Any FAIL, or a different number: stop, and do not switch sign-in on (RUNBOOK.md).',
    '--',
    `-- Contents: ${files.join(', ')}.`,
    '',
  ].join('\n');
}

function rlsHeader(checks) {
  return [
    `-- hushmallow · production · RLS CHECK (run after ${MIGRATIONS_NAME})`,
    '--',
    '-- GENERATED by hushmallow/tools/auth/bundle-sql.mjs: supabase/tests/rls_check.sql, byte for byte, below.',
    '-- Paste the whole file into a new query in the Supabase SQL editor and Run (role `postgres`). The',
    `-- result is one column, rls_check: a PASS line per check, and the last line must read`,
    `--   ALL ${checks} CHECKS PASSED. Everything this script created was rolled back.`,
    '-- Nothing is left behind and no email is sent. Any FAIL: do not switch sign-in on (RUNBOOK.md).',
    '',
  ].join('\n');
}

/** Both files' text, built from the sources now (pure apart from reading them). */
export function bundleSql({ migrationsDir = MIGRATIONS_DIR, rlsCheckFile = RLS_CHECK_FILE } = {}) {
  const files = migrationFiles(migrationsDir);
  const rls = readFileSync(rlsCheckFile, 'utf8');
  const checks = countRlsChecks(rls);
  let all = migrationsHeader(files, checks);
  for (const f of files) {
    const src = readFileSync(join(migrationsDir, f), 'utf8');
    // (every migration ends with a line break; refuse rather than glue two statements together)
    if (!src.endsWith('\n')) throw new Error(`supabase/migrations/${f} does not end with a line break`);
    all += `\n-- ======== supabase/migrations/${f} ========\n${src}`;
  }
  return { files: { [MIGRATIONS_NAME]: all, [RLS_CHECK_NAME]: rlsHeader(checks) + rls }, migrations: files, checks };
}

/** The names of the files in `dir` that differ from a fresh bundle (missing ones included). */
export function staleFiles(dir = OUT_DIR, built = bundleSql()) {
  return Object.entries(built.files).filter(([name, text]) => !existsSync(join(dir, name)) || readFileSync(join(dir, name), 'utf8') !== text).map(([name]) => name);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  const i = args.indexOf('--out');
  const out = i >= 0 && args[i + 1] ? resolve(args[i + 1]) : OUT_DIR;
  const built = bundleSql();
  if (args.includes('--check')) {
    const stale = staleFiles(out, built);
    if (stale.length) { console.error(`bundle-sql: out of date: ${stale.join(', ')} (run node hushmallow/tools/auth/bundle-sql.mjs)`); process.exit(1); }
    console.log(`bundle-sql: up to date (${built.migrations.length} migrations, ${built.checks} RLS checks)`);
  } else {
    mkdirSync(out, { recursive: true });
    for (const [name, text] of Object.entries(built.files)) writeFileSync(join(out, name), text);
    console.log(`bundle-sql: wrote ${Object.keys(built.files).join(', ')} (${built.migrations.length} migrations, ${built.checks} RLS checks)`);
  }
}
